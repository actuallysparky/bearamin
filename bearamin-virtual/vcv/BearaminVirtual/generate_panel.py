#!/usr/bin/env python3
"""Regenerate the Rack panel artwork and control positions from the saved 10HP PCB."""

from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent
BOARD = ROOT.parents[1].parent / "bearamin-lite/hw/bearcv-10hp/bearcv-10hp_newpots.kicad_pcb"
PANEL = ROOT / "res/BearaminVirtual.svg"
LAYOUT = ROOT / "src/panel_layout.hpp"
WIDTH, HEIGHT = 150.0, 380.0  # Rack pixels: 10HP x 128.5 mm
REFS = (
    "J_X_UNI", "J_Y_UNI", "J_Z_UNI", "J_X_BI", "J_Y_BI", "J_Z_BI",
    "J_PRES", "J_SPANK", "RV_RANGE", "RV_SLEW",
)


def footprint_positions(board: str) -> dict[str, tuple[float, float]]:
    found = {}
    for block in board.split("\n\t(footprint ")[1:]:
        reference = re.search(r'\(property "Reference" "([^"]+)"', block)
        position = re.search(r'\(translate ([-\d.]+) ([-\d.]+)\)', block)
        if reference and position and reference.group(1) in REFS:
            found[reference.group(1)] = (float(position.group(1)), float(position.group(2)))
    if set(found) != set(REFS):
        raise ValueError(f"Missing PCB positions: {sorted(set(REFS) - set(found))}")
    return found


def board_origin(board: str) -> tuple[float, float]:
    # The panel's upper-left Edge.Cuts lines define the physical origin.
    edges = re.findall(
        r'\(gr_line\s+\(start ([-\d.]+) ([-\d.]+)\)\s+'
        r'\(end ([-\d.]+) ([-\d.]+)\).*?\(layer "Edge.Cuts"\)',
        board, re.S,
    )
    if not edges:
        raise ValueError("No Edge.Cuts lines on the PCB")
    return min(float(v) for a, _, c, _ in edges for v in (a, c)), min(
        float(v) for _, b, _, d in edges for v in (b, d)
    )


def main() -> None:
    board = BOARD.read_text()
    positions = footprint_positions(board)
    origin_x, origin_y = board_origin(board)
    with tempfile.TemporaryDirectory() as temporary:
        plotted = Path(temporary) / "faceplate.svg"
        cli = shutil.which("kicad-cli") or "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli"
        subprocess.run([
            cli, "pcb", "export", "svg", "--layers", "F.SilkS,F.Cu,Edge.Cuts",
            "--mode-single", "--page-size-mode", "2", "--exclude-drawing-sheet",
            "-o", str(plotted), str(BOARD),
        ], check=True)
        svg = plotted.read_text()
    view = re.search(r'viewBox="0\.0000 0\.0000 ([\d.]+) ([\d.]+)"', svg)
    if not view:
        raise ValueError("Unexpected KiCad SVG viewBox")
    svg_w, svg_h = map(float, view.groups())
    margin_x = (svg_w - 50.4) / 2
    margin_y = (svg_h - 128.5) / 2
    scale_x, scale_y = WIDTH / svg_w, HEIGHT / svg_h
    # KiCad plots lettering as paths. Its invisible text copies are unnecessary.
    artwork = svg[svg.index("<g "):svg.rindex("</svg>")]
    artwork = re.sub(r"<text\b[^>]*>.*?</text>", "", artwork, flags=re.S)
    artwork = artwork.replace("#C83434", "#C9A24D")
    artwork = "\n".join(line.rstrip() for line in artwork.splitlines()) + "\n"
    PANEL.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="150" height="380" '
        'viewBox="0 0 150 380">\n'
        '<rect width="150" height="380" fill="#070809"/>\n'
        f'<g transform="scale({scale_x:.8f} {scale_y:.8f})">\n'
        f'{artwork}</g>\n</svg>\n'
    )

    def point(ref: str) -> str:
        x, y = positions[ref]
        return f"{{{(x - origin_x + margin_x) * scale_x:.5f}f, {(y - origin_y + margin_y) * scale_y:.5f}f}}"

    output_points = ", ".join(point(ref) for ref in REFS[:8])
    # The 22 x 22 mm matrix aperture is centered at PCB (35.068301, 99.911226).
    center_x = (positions["J_Y_UNI"][0] - origin_x + margin_x) * scale_x
    center_y = (positions["RV_RANGE"][1] - origin_y + margin_y) * scale_y
    LAYOUT.write_text(
        "// Generated by generate_panel.py from the saved 10HP faceplate PCB.\n"
        "#pragma once\n"
        "namespace panel_layout {\n"
        "struct Point { float x, y; };\n"
        f"constexpr Point outputs[8] = {{{output_points}}};\n"
        f"constexpr Point range = {point('RV_RANGE')};\n"
        f"constexpr Point slew = {point('RV_SLEW')};\n"
        f"constexpr Point fieldTopLeft = {{{center_x - 11 * scale_x:.5f}f, {center_y - 11 * scale_y:.5f}f}};\n"
        f"constexpr Point fieldSize = {{{22 * scale_x:.5f}f, {22 * scale_y:.5f}f}};\n"
        "}\n"
    )


if __name__ == "__main__":
    main()
